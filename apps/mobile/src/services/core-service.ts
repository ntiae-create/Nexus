import { z } from "zod";
import {
  conversationSchema,
  coreExecutionInspectionSchema,
  coreExecutionResponseSchema,
  coreRunSchema,
  messageSchema,
  type Conversation,
  type CoreExecutionInspection,
  type CoreExecutionResponse,
  type CoreRun,
  type Message,
} from "@nexus/shared";
import { ApiError, type ApiClient } from "./api-client.js";

/**
 * Thin transport layer over the NEXUS CORE routes already exposed by the backend
 * (`apps/server/src/routes/core.ts`). No route is added or changed here: every path,
 * field and status code below mirrors the frozen contract.
 *
 * Rules this module guarantees:
 * - every payload is validated against the shared Zod schema, so the UI never renders a
 *   body that does not match the contract (`invalid_response` instead of silent bad data);
 * - the Bearer token is forwarded per request and never stored, logged or echoed;
 * - no assistant reply is ever produced locally — a missing server message is an error.
 */

/** Wire envelopes of the CORE routes, mirrored field-for-field. */
export const conversationsEnvelopeSchema = z.object({
  conversations: z.array(conversationSchema),
});

export const conversationEnvelopeSchema = z.object({
  conversation: conversationSchema,
});

export const messagesEnvelopeSchema = z.object({
  messages: z.array(messageSchema),
});

export const executionsEnvelopeSchema = z.object({
  executions: z.array(coreRunSchema),
});

/** `execute: false` path: the message is persisted but no execution runs. */
export const appendMessageResponseSchema = z.object({
  message: messageSchema,
  execution: z.null(),
});

export type AppendMessageResponse = z.infer<typeof appendMessageResponseSchema>;

const CONVERSATIONS_ROUTE = "/v1/conversations";

function invalidResponse(what: string): ApiError {
  return new ApiError({
    kind: "invalid_response",
    message: `O servidor respondeu a ${what} em um formato inesperado.`,
  });
}

function parseOrThrow<T>(schema: z.ZodType<T>, payload: unknown, what: string): T {
  const parsed = schema.safeParse(payload);
  if (!parsed.success) throw invalidResponse(what);
  return parsed.data;
}

/**
 * `POST /v1/conversations` body.
 *
 * `assistantIds` uses the canonical catalog UUIDs (migration `00001`), because the CORE
 * requires the target assistant to participate in the conversation
 * (`ASSISTANT_NOT_IN_CONVERSATION` otherwise). `assistantKey` is not accepted here.
 */
export interface CreateConversationInput {
  readonly title?: string;
  readonly assistantIds?: readonly string[];
}

/**
 * `POST /v1/conversations/:id/messages` body.
 *
 * `requestId` is a UUID supplied by the caller and `idempotencyKey` must be stable across
 * retries of the same message and never reused for a different one; the CORE derives
 * `core:<conversationId>:<idempotencyKey>` and fingerprints the payload, answering
 * `IDEMPOTENCY_CONFLICT` when the same key arrives with different content.
 */
export interface SendMessageInput {
  readonly content: readonly { readonly type: "text"; readonly text: string }[];
  readonly requestId: string;
  readonly idempotencyKey: string;
  readonly assistantKey?: "yui" | "alice" | "schwi";
  readonly assistantId?: string;
}

export interface CoreService {
  /** `GET /v1/conversations` — owner conversations, newest first (server ordering). */
  listConversations(token: string, options?: { signal?: AbortSignal }): Promise<readonly Conversation[]>;
  /** `GET /v1/conversations/:id`. */
  getConversation(
    token: string,
    conversationId: string,
    options?: { signal?: AbortSignal },
  ): Promise<Conversation>;
  /** `POST /v1/conversations`. */
  createConversation(
    token: string,
    input: CreateConversationInput,
    options?: { signal?: AbortSignal },
  ): Promise<Conversation>;
  /** `GET /v1/conversations/:id/messages` (optionally only messages after a sequence). */
  listMessages(
    token: string,
    conversationId: string,
    options?: { afterSequence?: number; signal?: AbortSignal },
  ): Promise<readonly Message[]>;
  /**
   * `POST /v1/conversations/:id/messages`.
   *
   * Default (`execute` omitted) runs the CORE: the server persists the user message, calls
   * the provider and persists the assistant message atomically, then answers with the full
   * execution. The returned `assistantMessage` is the persisted reply — never generated by
   * the client.
   */
  sendMessage(
    token: string,
    conversationId: string,
    input: SendMessageInput,
    options?: { signal?: AbortSignal },
  ): Promise<CoreExecutionResponse>;
  /** `GET /v1/conversations/:id/executions` — the conversation's runs. */
  listExecutions(
    token: string,
    conversationId: string,
    options?: { signal?: AbortSignal },
  ): Promise<readonly CoreRun[]>;
  /** `GET /v1/executions/:runId` — steps, results and child executions. */
  getExecution(
    token: string,
    runId: string,
    options?: { signal?: AbortSignal },
  ): Promise<CoreExecutionInspection>;
  /** `POST /v1/executions/:runId/cancel` — authoritative cancellation in the CORE. */
  cancelExecution(
    token: string,
    runId: string,
    options?: { signal?: AbortSignal },
  ): Promise<CoreExecutionInspection>;
}

/** Encodes a conversation id for a path segment without trusting it blindly. */
function conversationPath(conversationId: string, suffix = ""): string {
  return `${CONVERSATIONS_ROUTE}/${encodeURIComponent(conversationId)}${suffix}`;
}

export function createCoreService(client: ApiClient): CoreService {
  return {
    async listConversations(token, options = {}) {
      const payload = await client.get<unknown>(CONVERSATIONS_ROUTE, {
        token,
        ...(options.signal ? { signal: options.signal } : {}),
      });
      const parsed = parseOrThrow(
        conversationsEnvelopeSchema,
        payload,
        "a lista de conversas",
      );
      return parsed.conversations;
    },

    async getConversation(token, conversationId, options = {}) {
      const payload = await client.get<unknown>(conversationPath(conversationId), {
        token,
        ...(options.signal ? { signal: options.signal } : {}),
      });
      return parseOrThrow(conversationEnvelopeSchema, payload, "a conversa").conversation;
    },

    async createConversation(token, input, options = {}) {
      const body: Record<string, unknown> = {};
      if (input.title !== undefined) body.title = input.title;
      if (input.assistantIds && input.assistantIds.length > 0) {
        body.assistantIds = [...input.assistantIds];
      }
      const payload = await client.post<unknown>(CONVERSATIONS_ROUTE, body, {
        token,
        ...(options.signal ? { signal: options.signal } : {}),
      });
      return parseOrThrow(conversationEnvelopeSchema, payload, "a criação da conversa")
        .conversation;
    },

    async listMessages(token, conversationId, options = {}) {
      const query =
        options.afterSequence !== undefined
          ? `?afterSequence=${encodeURIComponent(String(options.afterSequence))}`
          : "";
      const payload = await client.get<unknown>(
        conversationPath(conversationId, `/messages${query}`),
        { token, ...(options.signal ? { signal: options.signal } : {}) },
      );
      return parseOrThrow(messagesEnvelopeSchema, payload, "o histórico de mensagens").messages;
    },

    async sendMessage(token, conversationId, input, options = {}) {
      const body: Record<string, unknown> = {
        content: input.content.map((part) => ({ type: part.type, text: part.text })),
        requestId: input.requestId,
        idempotencyKey: input.idempotencyKey,
      };
      if (input.assistantKey) body.assistantKey = input.assistantKey;
      if (input.assistantId) body.assistantId = input.assistantId;

      // A full execution can take up to the CORE's provider timeout (60 s default) plus
      // persistence, so the per-request budget is raised above the client default.
      const payload = await client.post<unknown>(
        conversationPath(conversationId, "/messages"),
        body,
        {
          token,
          timeoutMs: EXECUTION_TIMEOUT_MS,
          ...(options.signal ? { signal: options.signal } : {}),
        },
      );
      return parseOrThrow(
        coreExecutionResponseSchema,
        payload,
        "a resposta da execução",
      ) as CoreExecutionResponse;
    },

    async listExecutions(token, conversationId, options = {}) {
      const payload = await client.get<unknown>(
        conversationPath(conversationId, "/executions"),
        { token, ...(options.signal ? { signal: options.signal } : {}) },
      );
      return parseOrThrow(executionsEnvelopeSchema, payload, "a lista de execuções")
        .executions;
    },

    async getExecution(token, runId, options = {}) {
      const payload = await client.get<unknown>(
        `/v1/executions/${encodeURIComponent(runId)}`,
        { token, ...(options.signal ? { signal: options.signal } : {}) },
      );
      return parseOrThrow(coreExecutionInspectionSchema, payload, "a execução");
    },

    async cancelExecution(token, runId, options = {}) {
      const payload = await client.post<unknown>(
        `/v1/executions/${encodeURIComponent(runId)}/cancel`,
        undefined,
        { token, ...(options.signal ? { signal: options.signal } : {}) },
      );
      return parseOrThrow(coreExecutionInspectionSchema, payload, "o cancelamento");
    },
  };
}

/**
 * Request budget for a message that triggers a CORE execution.
 *
 * The server's own provider timeout is 60 s (see `NEXUS_CORE_LIMITS.providerTimeoutMs`);
 * the extra headroom covers admission, persistence and transport, so the client does not
 * give up while the server is still legitimately working.
 */
export const EXECUTION_TIMEOUT_MS = 90_000;
